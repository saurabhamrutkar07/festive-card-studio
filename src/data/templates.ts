/** Designs for a mode and occasion (business designs serve every occasion). */
export const templatesFor = (mode: CardMode, occasion: Occasion): CardTemplate[] =>
  CARD_TEMPLATES.filter((t) => t.mode === mode && t.occasions.includes(occasion));

export const categoriesFor = (mode: CardMode, occasion: Occasion): TemplateCategory[] => [
  ...new Set(templatesFor(mode, occasion).map((t) => t.category)),
];

export const templatesForMode = (mode: CardMode): CardTemplate[] => CARD_TEMPLATES.filter((t) => t.mode === mode);

export const categoriesForMode = (mode: CardMode): TemplateCategory[] => [...new Set(templatesForMode(mode).map((t) => t.category))];

export const TEMPLATE_CATEGORIES: TemplateCategory[] = categoriesForMode('personal');

export const CARD_DIMENSIONS: Record<CardFormat, CardDimensions> = {
  portrait: { width: 1080, height: 1350, label: 'Portrait · 1080 × 1350' },
  square: { width: 1080, height: 1080, label: 'Square · 1080 × 1080' },
  landscape: { width: 1920, height: 1080, label: 'Landscape · 1920 × 1080' },
};

export const getTemplateById = (id: string): CardTemplate =>
  CARD_TEMPLATES.find((t) => t.id === id) ?? CARD_TEMPLATES[0];
